#!/usr/bin/env python3
"""Five presentations of one set of facts — the silent supplier fixture (C registered 17 Feb 2025,
D registered 1 Sep 2025, nothing says D replaced C) — differing only in WHERE and HOW the succession
is written. Same four documents, same truth, same five questions. Generated, so the difference between
any two variants is exactly what this file says it is.

  a  silent        as the fixture stands: dates in the prose only; map rows are each document's own line
  d  dates-in-row  the map rows also carry each decision's date — dates, no succession words
  b  doc-header    the two documents open with RFC-style lines: Supersedes: / Superseded by:
  c  row-statement the map rows state the succession in words, with the period each was in force
  e  both          b + c
"""
import copy, pathlib, yaml
HERE = pathlib.Path(__file__).parent
base = yaml.safe_load((HERE.parent / "supplier-selection-silent.yaml").read_text(encoding="utf-8"))
C, D = "y-supplier-c-approved", "y-supplier-d-approved"
ASOF = [
  {"q": "Which supplier was the registered source for the Y component for an order placed in April 2025?",
   "answer": "Supplier C, registered 17 February 2025 and still the source in April 2025",
   "operative": C, "distractors": [D]},
  {"q": "What delivery window applied to a Y order placed in March 2025?",
   "answer": "Fifteen working days, under the February registration",
   "operative": C, "distractors": [D, "y-annual-sourcing-note-2025"]},
]
OWN = {d["id"]: d["one_liner"] for d in base["documents"]}
DATE = {C: "decided 17 February 2025", D: "decided 1 September 2025"}
STATEMENT = {
  D: "The registration in force for Y: Supplier D since 1 September 2025 — the terms any order placed now is under",
  C: "The earlier registration for Y, Supplier C from 17 February 2025 — replaced on 1 September 2025 and not the source for a new order",
}
HEADER = {
  D: "Supersedes: y-supplier-c-approved (Supplier C approved for the Y component), from 1 September 2025\n\n",
  C: "Superseded by: y-supplier-d-approved (Supplier D approved for the Y component), from 1 September 2025\n\n",
}
ADV = {D: "current", C: "replaced"}
ORDER = [D, C, "y-inspection-rejects-batch", "y-annual-sourcing-note-2025"]   # current first, as a changelog

def fixture(key, header):
    fx = copy.deepcopy(base)
    fx["id"] = f"pres-{key}"
    fx["contributed_by"] = "generated by eval/fixtures/pres/make.py from supplier-selection-silent"
    fx["questions"] = fx["questions"] + copy.deepcopy(ASOF)
    if header:
        for d in fx["documents"]:
            if d["id"] in HEADER:
                lines = d["body"].split("\n", 1)        # keep the "# Title" line first, the header under it
                d["body"] = lines[0] + "\n\n" + HEADER[d["id"]] + lines[1].lstrip("\n")
    return fx

def mapfile(key, rows):
    return {"fixture": f"pres-{key}", "area": "procurement",
            "area_use_when": "how far up this amount has to be approved · how to register a new vendor · how many quotes are needed · where the signed contract is kept",
            "node": {"id": "sec-y-component-sourcing", "name": "Sourcing the Y component", "kind": "topic",
                     "parent": "sec-vendor-registration-cases",
                     "one_liner": "The registrations and records for the Y component's supplier",
                     "children": [{"id": i, "advertise": ADV.get(i, "history"), "one_liner": rows[i]} for i in ORDER]}}

VARIANTS = {
  "a": (False, {i: OWN[i] for i in ORDER}),
  "d": (False, {i: OWN[i] + (f" — {DATE[i]}" if i in DATE else "") for i in ORDER}),
  "b": (True,  {i: OWN[i] for i in ORDER}),
  "c": (False, {i: STATEMENT.get(i, OWN[i]) for i in ORDER}),
  "e": (True,  {i: STATEMENT.get(i, OWN[i]) for i in ORDER}),
}
for key, (header, rows) in VARIANTS.items():
    (HERE / f"pres-{key}.yaml").write_text(yaml.safe_dump(fixture(key, header), sort_keys=False, allow_unicode=True, width=100), encoding="utf-8")
    (HERE / f"pres-{key}.map.yaml").write_text(yaml.safe_dump(mapfile(key, rows), sort_keys=False, allow_unicode=True, width=100), encoding="utf-8")
    print("wrote", key)
